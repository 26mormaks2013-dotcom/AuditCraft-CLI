"""Proof-of-Concept (PoC) generator for Foundry and Anchor test scaffolding.

Given an exploit type and a target name, produce a ready-to-run test file.
Supported kinds: ``reentrancy``, ``flashloan``, ``access-control``, ``custom``.
"""

from __future__ import annotations

from dataclasses import dataclass
from typing import Final

POC_TYPES: Final[tuple[str, ...]] = (
    "reentrancy",
    "flashloan",
    "access-control",
    "custom",
)

LANGUAGES: Final[tuple[str, ...]] = ("solidity", "anchor")


@dataclass(frozen=True)
class PocResult:
    """Rendered PoC with target language and filename suggestion."""

    language: str
    filename: str
    content: str


