_TITLES: dict[str, str] = {
    "reentrancy": "Reentrancy exploit",
    "flashloan": "Flashloan exploit",
    "access-control": "Access-control bypass",
    "custom": "Custom exploit",
}


def _camel(name: str) -> str:
    parts = [p for p in name.replace("-", "_").split("_") if p]
    return "".join(p[:1].upper() + p[1:] for p in parts) or "Target"


def _snake(name: str) -> str:
    out: list[str] = []
    for ch in name:
        if ch.isupper() and out and out[-1] != "_":
            out.append("_")
        out.append(ch.lower())
    return "".join(out).replace("-", "_").strip("_")


def generate(
    kind: str,
    target: str,
    language: str = "solidity",
) -> PocResult:
    """Render a PoC for ``kind`` targeting contract ``target``.

    ``language`` is either ``solidity`` (Foundry ``.t.sol``) or ``anchor`` (TS).
    """
    if kind not in POC_TYPES:
        raise ValueError(
            f"Unknown PoC type {kind!r}; expected one of {', '.join(POC_TYPES)}"
        )
    if language not in LANGUAGES:
        raise ValueError(
            f"Unknown language {language!r}; expected one of {', '.join(LANGUAGES)}"
        )
    if not target or not target.replace("_", "").isalnum():
        raise ValueError(f"Invalid target name {target!r}")

    title = _TITLES[kind]
    camel = _camel(target)

    if language == "solidity":
        contract_name = f"{camel}PoCTest"
        header = _FOUNDRY_HEADER.format(
            target=target, title=title, contract_name=contract_name
        )
        body = _FOUNDRY_BODIES[kind]
        content = header + body + _FOUNDRY_FOOTER
        return PocResult(
            language="solidity",
            filename=f"{camel}PoC.t.sol",
            content=content,
        )

    content = _ANCHOR_TEMPLATE.format(
        title=title,
        target=camel,
        target_snake=_snake(target),
    )
    return PocResult(
        language="anchor",
        filename=f"{_snake(target)}_poc.ts",
        content=content,
    )
